#!/usr/bin/env python3
"""Extract the mdev.conf parse tables verbatim from the reference mdevd.c
into Rust syntax. Test tool: the generated file is checked in; rerunning
must be a no-op (verified in P6). Usage: gen-tables.py MDEVD_C OUT_RS"""
import re
import sys

src = open(sys.argv[1]).read()

def table(rows, cols, ctype):
    m = re.search(
        r"static [\w ]+ const table\[%d\]\[%d\]\s*=\s*\{(.*?)\} ;" % (rows, cols),
        src,
        re.S,
    )
    assert m, ctype
    nums = re.findall(r"0x[0-9a-fA-F]+", m.group(1))
    assert len(nums) == rows * cols, (ctype, len(nums))
    return [nums[i * cols : (i + 1) * cols] for i in range(rows)]

def cclass():
    strings = re.findall(r'classtable\[65\] = "(.*?)"', src)
    assert len(strings) == 2, strings
    for s in strings:
        assert re.fullmatch(r"[ -~]+", s) and '"' not in s and "\\" not in s, s
    return strings

first = table(5, 9, "firstpass")
second = table(30, 19, "secondpass")
c1, c2 = cclass()

out = []
out.append("// GENERATED by tools/gen-tables.py from src/mdevd/mdevd.c — do not hand-edit.")
out.append("// Rerun must be a no-op (checked in P6).")
out.append("pub const FIRSTPASS_CCLASS: &[u8; 65] = b\"%s\";" % c1)
out.append("pub const FIRSTPASS_TABLE: [[u8; 9]; 5] = [")
for r in first:
    out.append("    [%s]," % ", ".join("0x%02x" % int(x, 16) for x in r))
out.append("];")
out.append("pub const SECONDPASS_CCLASS: &[u8; 65] = b\"%s\";" % c2)
out.append("pub const SECONDPASS_TABLE: [[u32; 19]; 30] = [")
for r in second:
    out.append("    [%s]," % ", ".join("0x%08x" % int(x, 16) for x in r))
out.append("];")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("gen-tables: wrote %s" % sys.argv[2])
