#!/usr/bin/env python3
"""Extract parse tables verbatim from upstream mdevd.c into Rust syntax.
Test tool: generated files are checked in; rerunning must be a no-op.
Usage: gen-tables.py MDEVD_C CONFIG_RS ENGINE_RS, where MDEVD_C is an
upstream mdevd 0.1.8.3 mdevd.c (the in-repo copy was removed when the
port went independent; the tables in src/config/tables.rs and
src/engine/tables.rs are frozen and must not be hand-edited)."""
import re
import sys

src = open(sys.argv[1]).read()

def table(rows, cols, ctype):
    m = re.search(
        r"static [\w ]+ const table\[%d\]\[%d\]\s*=\s*\{(.*?)\} ;" % (rows, cols),
        src,
        re.S,
    )
    assert m, ctype
    nums = re.findall(r"0x[0-9a-fA-F]+", m.group(1))
    assert len(nums) == rows * cols, (ctype, len(nums))
    return [nums[i * cols : (i + 1) * cols] for i in range(rows)]

def cclass(size):
    m = re.search(r'classtable\[%d\] = "([^"]*)"' % size, src)
    assert m, size
    s = m.group(1)
    assert re.fullmatch(r"[ -~]+", s) and '"' not in s and "\\" not in s, s
    return s

first = table(5, 9, "firstpass")
second = table(30, 19, "secondpass")
c1 = cclass(65)
c65b = [m for m in re.findall(r'classtable\[65\] = "([^"]*)"', src)]
assert len(c65b) == 2
c2 = c65b[1]
fmt_table = table(2, 4, "format")
fmt_cc = cclass(58)

out = []
out.append("// GENERATED by tools/gen-tables.py from src/mdevd/mdevd.c — do not hand-edit.")
out.append("// Rerun must be a no-op (checked in P6).")
out.append("pub const FIRSTPASS_CCLASS: &[u8; 65] = b\"%s\";" % c1)
out.append("pub const FIRSTPASS_TABLE: [[u8; 9]; 5] = [")
for r in first:
    out.append("    [%s]," % ", ".join("0x%02x" % int(x, 16) for x in r))
out.append("];")
out.append("pub const SECONDPASS_CCLASS: &[u8; 65] = b\"%s\";" % c2)
out.append("pub const SECONDPASS_TABLE: [[u32; 19]; 30] = [")
for r in second:
    out.append("    [%s]," % ", ".join("0x%08x" % int(x, 16) for x in r))
out.append("];")
open(sys.argv[2], "w").write("\n".join(out) + "\n")

out = []
out.append("// GENERATED by tools/gen-tables.py from src/mdevd/mdevd.c — do not hand-edit.")
out.append("pub const FORMAT_CCLASS: &[u8; 58] = b\"%s\";" % fmt_cc)
out.append("pub const FORMAT_TABLE: [[u8; 4]; 2] = [")
for r in fmt_table:
    out.append("    [%s]," % ", ".join("0x%02x" % int(x, 16) for x in r))
out.append("];")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
print("gen-tables: wrote %s %s" % (sys.argv[2], sys.argv[3]))
